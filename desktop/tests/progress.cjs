const assert=require('node:assert/strict');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {chromium}=require('playwright');
const root=path.join(__dirname,'../..');
const long=path.join(root,'desktop/build/progress-long.png');
execFileSync(path.join(root,'desktop/.venv/Scripts/python.exe'),['-c',"import cv2,numpy as np; im=cv2.imread('desktop/tests/samples/pdd_orders.jpg'); cv2.imwrite('desktop/build/progress-long.png',np.concatenate([im]*5,axis=0))"],{cwd:root});
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try {
  const p=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];p.on('pageerror',e=>errors.push(e.message));
  await p.goto(process.env.XUNJI_TEST_URL);await p.waitForFunction(()=>typeof S!=='undefined'&&S);
  assert.match(await p.evaluate(()=>dbInfo().path),/ui-test/);
  await p.evaluate(()=>{
   window.progressTrace=[];window.resultTrace=[];
   const progress=window.onOcrProgress,result=window.onOcrLocal;
   window.onOcrProgress=(id,json)=>{progressTrace.push({id,...JSON.parse(json)});progress(id,json);};
   window.onOcrLocal=(id,json)=>{resultTrace.push({id,...JSON.parse(json)});result(id,json);};
  });
  await p.waitForTimeout(800);
  assert.deepEqual(await p.evaluate(()=>D.ocrReadyProfiles),[],'Ordinary bookkeeping must not warm OCR');
  assert.equal(await p.evaluate(()=>D.ocrWarm),null);
  await p.evaluate(()=>{S=initData(false);resetTxnOrder();S.settings.desktopOcrProfile='accurate';openOcr();});
  await p.waitForFunction(()=>D.ocrReadyProfiles.includes('balanced')&&!D.ocrWarm,null,{timeout:90000});
  assert.equal(await p.evaluate(()=>desktopOcrProfile()),'balanced');
  await p.locator('#ocrFile').setInputFiles([long,path.join(root,'desktop/tests/samples/douyin_orders.jpg')]);
  await p.waitForFunction(()=>OC.busy&&OC.progress?.stage==='recognizing'&&OC.progress.total>1&&OC.progress.completed>0,null,{timeout:90000});
  assert(await p.locator('#ocrTaskProgress progress').evaluate(el=>el.value>0&&el.max>1));
  await p.setViewportSize({width:1024,height:720});
  const visible=await p.locator('#ocrTaskProgress progress').boundingBox();assert(visible.y+visible.height<=720,'Progress stays visible on a short desktop window');
  await p.setViewportSize({width:1440,height:900});
  await p.screenshot({path:path.join(root,'desktop/build/screenshots/ocr-progress.png')});
  await p.locator('.desk-nav [data-page=home]').click();
  await p.keyboard.press('Control+n');
  const draft=p.locator('textarea[aria-label=备注]');
  await draft.fill('识别在后台继续，这份草稿不能被刷新');
  await p.locator('#deskAmount').fill('88.88');await draft.focus();
  await p.evaluate(()=>window.draftNode=document.querySelector('textarea[aria-label=备注]'));
  await p.waitForFunction(()=>!OC.busy&&OC.imgs===2,null,{timeout:90000});
  assert.equal(await p.evaluate(()=>stack.at(-1).name),'add');
  assert.equal(await draft.inputValue(),'识别在后台继续，这份草稿不能被刷新');
  assert.equal(await p.locator('#deskAmount').inputValue(),'88.88');
  assert(await p.evaluate(()=>draftNode===document.querySelector('textarea[aria-label=备注]')&&document.activeElement===draftNode),'Background progress must preserve the form DOM and focus');
  await p.locator('#deskOcrTask').getByText('识别已完成',{exact:true}).waitFor();
  const actual=await p.evaluate(()=>resultTrace.filter(r=>/^o\d+$/.test(r.id)));
  assert.equal(actual.length,2);assert(actual.every(r=>r.cached&&r.load_ms===0));
  const stages=await p.evaluate(()=>progressTrace.filter(e=>e.id===resultTrace.find(r=>/^o\d+$/.test(r.id)).id&&e.stage==='recognizing'));
  assert(stages.length>2);assert.equal(stages[0].completed,0);assert.equal(stages.at(-1).completed,stages.at(-1).total);
  assert(stages.every((s,i)=>!i||s.completed>=stages[i-1].completed));
  const resultCount=await p.evaluate(()=>OC.items.length);
  await p.locator('#deskOcrDismiss').click();
  assert(await p.locator('#deskOcrTask').isHidden());
  await p.locator('.desk-nav [data-page=imports]').click();
  await p.locator('.desk-nav [data-page=home]').click();
  await p.locator('#deskOcrResume').getByText(`查看识别结果 · ${resultCount} 笔`,{exact:true}).click();
  assert.equal(await p.evaluate(()=>OC.items.length),resultCount,'Dismissal and navigation must preserve recognition results');
  assert.equal(await p.locator('.desk-ocr-profiles button').count(),0);
  assert(await p.evaluate(()=>OC.items.length>3));
  await p.locator('#deskOcrModelState').getByText(/模型已就绪/).waitFor();
  assert.equal(await p.locator('#ocrTaskProgress progress').count(),0);
  const retained=await p.evaluate(()=>JSON.stringify(OC.items));
  await p.evaluate(()=>window.onOcrReleased());
  assert.equal(await p.evaluate(()=>JSON.stringify(OC.items)),retained);
  assert.deepEqual(await p.evaluate(()=>D.ocrReadyProfiles),[]);
  assert.deepEqual(errors,[]);
  console.log('PASS: lazy prewarm, single recommended model, release preserves results, real segment progress, multi-image work across navigation, draft/focus preservation and result return');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
